bool partialMode = false;

void waitBusy() {
  uint32_t t0 = millis();
  while (digitalRead(PIN_EPD_BUSY) == HIGH) {  // HIGH = beschäftigt
    if (millis() - t0 > 5000) break;
    delay(2);
  }
}

void cmd(uint8_t c) {
  digitalWrite(PIN_EPD_DC, LOW);
  digitalWrite(PIN_EPD_CS, LOW);
  epdSpi.beginTransaction(kSpi);
  epdSpi.transfer(c);
  epdSpi.endTransaction();
  digitalWrite(PIN_EPD_CS, HIGH);
}

void data(uint8_t d) {
  digitalWrite(PIN_EPD_DC, HIGH);
  digitalWrite(PIN_EPD_CS, LOW);
  epdSpi.beginTransaction(kSpi);
  epdSpi.transfer(d);
  epdSpi.endTransaction();
  digitalWrite(PIN_EPD_CS, HIGH);
}

void dataBlock(const uint8_t *buf, size_t len) {
  digitalWrite(PIN_EPD_DC, HIGH);
  digitalWrite(PIN_EPD_CS, LOW);
  epdSpi.beginTransaction(kSpi);
  epdSpi.writeBytes(buf, len);
  epdSpi.endTransaction();
  digitalWrite(PIN_EPD_CS, HIGH);
}

void hwReset() {
  digitalWrite(PIN_EPD_RST, HIGH);
  delay(50);
  digitalWrite(PIN_EPD_RST, LOW);
  delay(20);
  digitalWrite(PIN_EPD_RST, HIGH);
  delay(50);
  waitBusy();
}

void setLut(const uint8_t *lut) {
  cmd(0x32);
  dataBlock(lut, 153);
  waitBusy();
  cmd(0x3F); data(lut[153]);
  cmd(0x03); data(lut[154]);
  cmd(0x04); data(lut[155]); data(lut[156]); data(lut[157]);
  cmd(0x2C); data(lut[158]);
}

// Adressierung wie im Waveshare-Treiber (X aufsteigend, Y absteigend)
void setAddressing() {
  cmd(0x01);  // Driver output control
  data(0xC7); data(0x00); data(0x01);
  cmd(0x11);  // Data entry mode
  data(0x01);
  cmd(0x44);  // RAM X start/end
  data(0x00); data((EPD_W - 1) >> 3);
  cmd(0x45);  // RAM Y start/end
  data((EPD_H - 1) & 0xFF); data((EPD_H - 1) >> 8);
  data(0x00); data(0x00);
}

void setCursor() {
  cmd(0x4E); data(0x00);
  cmd(0x4F); data((EPD_H - 1) & 0xFF); data((EPD_H - 1) >> 8);
}

void initFull() {
  hwReset();
  cmd(0x12);  // SW reset
  waitBusy();
  setAddressing();
  cmd(0x3C); data(0x01);  // Border
  cmd(0x18); data(0x80);  // interner Temperatursensor
  cmd(0x22); data(0xB1);  // Temperatur + Waveform laden
  cmd(0x20);
  waitBusy();
  setCursor();
  setLut(WF_FULL);
  partialMode = false;
}

void initPartial() {
  hwReset();
  setLut(WF_PARTIAL);
  cmd(0x37);
  const uint8_t r37[10] = {0, 0, 0, 0, 0, 0x40, 0, 0, 0, 0};
  for (uint8_t b : r37) data(b);
  cmd(0x3C); data(0x80);
  cmd(0x22); data(0xC0);
  cmd(0x20);
  waitBusy();
  setAddressing();
  partialMode = true;
}

