namespace epd {

void begin() {
  pinMode(PIN_EPD_PWR, OUTPUT);
  digitalWrite(PIN_EPD_PWR, LOW);  // Display-Versorgung an
  pinMode(PIN_EPD_CS, OUTPUT);
  pinMode(PIN_EPD_DC, OUTPUT);
  pinMode(PIN_EPD_RST, OUTPUT);
  pinMode(PIN_EPD_BUSY, INPUT);
  digitalWrite(PIN_EPD_CS, HIGH);
  digitalWrite(PIN_EPD_RST, HIGH);
  delay(20);
  epdSpi.begin(PIN_EPD_SCK, -1, PIN_EPD_MOSI, -1);
}

void fullRefresh(const uint8_t *buf) {
  initFull();
  setCursor();
  cmd(0x24);
  dataBlock(buf, EPD_BUF_SIZE);
  setCursor();
  cmd(0x26);
  dataBlock(buf, EPD_BUF_SIZE);
  cmd(0x22); data(0xC7);
  cmd(0x20);
  waitBusy();
  initPartial();  // folgende Updates als Teil-Refresh
}

void partialRefresh(const uint8_t *buf) {
  if (!partialMode) initPartial();
  setCursor();
  cmd(0x24);
  dataBlock(buf, EPD_BUF_SIZE);
  cmd(0x22); data(0xCF);
  cmd(0x20);
  waitBusy();
}

void sleep() {
  cmd(0x10);
  data(0x01);
  partialMode = false;
}

}  // namespace epd
